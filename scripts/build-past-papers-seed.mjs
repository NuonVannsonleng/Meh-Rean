/**
 * Writes supabase/seed/past-papers.sql from src/data/past-papers/*.json.
 *
 *   npm run build:past-papers-seed
 *
 * Run the SQL after supabase/schema.sql and supabase/seed/curriculum.sql. It
 * upserts by id, so it is safe to run again, and never deletes anything. A
 * rerun updates the typed text but keeps a verification an admin has made.
 */

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { flattenCurriculum } from "../src/lib/curriculum.ts";
import { buildPastPapers } from "../src/lib/papers.ts";

const ROOT = new URL("../", import.meta.url);
const text = (value) => (value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`);
const num = (value) => (value === null || value === undefined ? "null" : String(value));

const chapters = [];
for (const file of (await readdir(new URL("src/data/curriculum/", ROOT))).filter((name) => name.endsWith(".json"))) {
  chapters.push(...flattenCurriculum(JSON.parse(await readFile(new URL(`src/data/curriculum/${file}`, ROOT), "utf8"))).chapters);
}

// One transaction per subject, so supabase/setup-parts/ can split between them.
const blocks = [];
const counts = { papers: 0, questions: 0, answers: 0 };
for (const file of (await readdir(new URL("src/data/past-papers/", ROOT))).filter((name) => name.endsWith(".json")).sort()) {
  const papers = buildPastPapers(JSON.parse(await readFile(new URL(`src/data/past-papers/${file}`, ROOT), "utf8")), chapters);
  const statements = [];
  for (const paper of papers) {
    counts.papers += 1;
    statements.push(`insert into public.exam_papers (id, subject_id, year, title_en, title_km, duration_minutes, duration_source, origin, source, verification)
values (${text(paper.id)}, ${text(paper.subjectId)}, ${paper.year}, ${text(paper.titleEn)}, ${text(paper.titleKm)}, ${num(paper.durationMinutes)}, ${text(paper.durationSource)}, 'official', ${text(paper.source)}, 'needs-review')
on conflict (id) do update set title_en = excluded.title_en, title_km = excluded.title_km, duration_minutes = excluded.duration_minutes,
  duration_source = excluded.duration_source, source = excluded.source;`);
    for (const { position, points, question: q } of paper.questions) {
      counts.questions += 1;
      statements.push(`insert into public.questions (id, chapter_id, topic_id, year, type, content, choices, images, difficulty, language, origin, source, verification)
values (${text(q.id)}, ${text(q.chapterId)}, null, ${q.year}, 'open', ${text(q.content)}, '[]'::jsonb, ${text(JSON.stringify(q.images.map(({ path, alt }) => ({ path, alt }))))}::jsonb, null, ${text(q.language)}, 'official-past-paper', ${text(q.source)}, 'needs-review')
on conflict (id) do update set chapter_id = excluded.chapter_id, content = excluded.content, images = excluded.images, language = excluded.language, source = excluded.source;
insert into public.exam_paper_questions (paper_id, question_id, position, points)
values (${text(paper.id)}, ${text(q.id)}, ${position}, ${num(points)})
on conflict (paper_id, question_id) do update set position = excluded.position, points = excluded.points;`);
      // The AI key never replaces an answer a teacher has written or checked.
      if (q.solution) {
        statements.push(`insert into public.question_solutions (question_id, answer, correct_choice, numeric_answer, numeric_tolerance, steps, origin, source, verification)
values (${text(q.id)}, ${text(q.solution.answer)}, null, null, null, ${text(JSON.stringify(q.solution.steps))}::jsonb, 'ai-generated', ${text(q.solution.source)}, 'needs-review')
on conflict (question_id) do update set answer = excluded.answer, steps = excluded.steps, source = excluded.source
  where public.question_solutions.origin = 'ai-generated' and public.question_solutions.verification <> 'verified';`);
        counts.answers += 1;
      }
    }
  }
  blocks.push(`-- ${file}\nbegin;\n${statements.join("\n\n")}\ncommit;`);
}

await mkdir(new URL("supabase/seed/", ROOT), { recursive: true });
await writeFile(
  new URL("supabase/seed/past-papers.sql", ROOT),
  `-- Generated by scripts/build-past-papers-seed.mjs from src/data/past-papers/. Do not edit by hand.
-- Real BacII papers, typed from copies shared online and not yet checked
-- against the Ministry's originals (needs-review). Answer keys only where
-- written by AI, marked ai-generated and needs-review. Run after supabase/schema.sql and supabase/seed/curriculum.sql;
-- safe to run again.

${blocks.join("\n\n")}
`,
);
console.log(`Wrote supabase/seed/past-papers.sql: ${counts.papers} papers, ${counts.questions} questions, ${counts.answers} AI answers`);
