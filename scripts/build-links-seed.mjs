#!/usr/bin/env node
/**
 * Writes supabase/seed/concept-links.sql from src/data/curriculum-links/*.json
 * (Learning OS 1.1). Run after editing a links file, then rebuild
 * supabase/setup-all.sql. The SQL inserts missing links only, so a link an
 * admin edited or checked keeps its changes.
 *
 *   node scripts/build-links-seed.mjs
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { expandLinks } from "../src/lib/conceptGraph.ts";

const SOURCE_DIR = new URL("../src/data/curriculum-links/", import.meta.url);
const OUT = new URL("../supabase/seed/concept-links.sql", import.meta.url);
const text = (value) => `'${String(value).replace(/'/g, "''")}'`;

const files = (await readdir(SOURCE_DIR)).filter((name) => name.endsWith(".json")).sort();
const parts = [];
let count = 0;
for (const file of files) {
  const seed = JSON.parse(await readFile(new URL(file, SOURCE_DIR), "utf8"));
  const links = expandLinks(seed);
  count += links.length;
  parts.push(
    `-- ${file}`,
    "insert into public.concept_links (from_topic, to_topic, kind, verification, source, created_by) values",
    links.map((link) => `  (${text(link.fromTopic)}, ${text(link.toTopic)}, ${text(link.kind)}, ${text(seed.verification)}, ${text(seed.source)}, null)`).join(",\n"),
    "on conflict (from_topic, to_topic, kind) do nothing;",
    "",
  );
}

await writeFile(
  OUT,
  [
    "-- Generated by scripts/build-links-seed.mjs from src/data/curriculum-links/.",
    "-- Do not edit by hand. Run after supabase/schema.sql and supabase/seed/curriculum.sql; safe to run again.",
    "",
    "begin;",
    ...parts,
    "commit;",
    "",
  ].join("\n"),
);
console.log(`supabase/seed/concept-links.sql: ${count} links from ${files.length} file(s)`);
