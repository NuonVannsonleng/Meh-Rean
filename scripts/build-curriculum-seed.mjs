/**
 * Writes supabase/seed/curriculum.sql from src/data/curriculum/*.json.
 *
 *   node scripts/build-curriculum-seed.mjs
 *
 * The JSON is the source; edit it, rerun this, then run the SQL in the
 * Supabase SQL editor after supabase/schema.sql. The SQL upserts by id, so it
 * is safe to run again. It never deletes: an entry removed from the JSON has
 * to be deleted by hand, so that questions linked to it are not lost.
 */

import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { flattenCurriculum } from "../src/lib/curriculum.ts";

const SOURCE_DIR = new URL("../src/data/curriculum/", import.meta.url);
const OUT = new URL("../supabase/seed/curriculum.sql", import.meta.url);

const text = (value) => (value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`);

function upsert(table, rows, columns) {
  if (!rows.length) return "";
  const names = Object.keys(columns);
  const values = rows.map((row) => `  (${names.map((name) => columns[name](row)).join(", ")})`).join(",\n");
  const updates = names.filter((name) => name !== "id").map((name) => `${name} = excluded.${name}`).join(", ");
  return `insert into public.${table} (${names.join(", ")}) values\n${values}\non conflict (id) do update set ${updates};\n`;
}

const files = (await readdir(SOURCE_DIR)).filter((name) => name.endsWith(".json")).sort();
const parts = [];
let counts = { versions: 0, tracks: 0, subjects: 0, chapters: 0, topics: 0 };

for (const file of files) {
  const seed = JSON.parse(await readFile(new URL(file, SOURCE_DIR), "utf8"));
  const flat = flattenCurriculum(seed);
  const topics = flat.chapters.flatMap((chapter) => chapter.topics);
  counts = {
    versions: counts.versions + 1,
    tracks: counts.tracks + flat.tracks.length,
    subjects: counts.subjects + flat.subjects.length,
    chapters: counts.chapters + flat.chapters.length,
    topics: counts.topics + topics.length,
  };
  const v = flat.version;
  parts.push(
    `-- ${file}`,
    upsert("curriculum_versions", [v], {
      id: (r) => text(r.id),
      title_en: (r) => text(r.titleEn),
      title_km: (r) => text(r.titleKm),
      country: (r) => text(r.country),
      grade: (r) => String(r.grade),
      verification: (r) => text(r.verification),
      source: (r) => text(r.source),
      notes: (r) => text(r.notes),
      updated_at: () => "now()",
    }),
    upsert("curriculum_tracks", flat.tracks, {
      id: (r) => text(r.id),
      version_id: (r) => text(r.versionId),
      key: (r) => text(r.key),
      name_en: (r) => text(r.nameEn),
      name_km: (r) => text(r.nameKm),
      sort: (r) => String(r.sort),
    }),
    upsert("curriculum_subjects", flat.subjects, {
      id: (r) => text(r.id),
      track_id: (r) => text(r.trackId),
      subject_key: (r) => text(r.subjectKey),
      name_en: (r) => text(r.nameEn),
      name_km: (r) => text(r.nameKm),
      sort: (r) => String(r.sort),
    }),
    upsert("curriculum_chapters", flat.chapters, {
      id: (r) => text(r.id),
      subject_id: (r) => text(r.subjectId),
      number: (r) => String(r.number),
      name_en: (r) => text(r.nameEn),
      name_km: (r) => text(r.nameKm),
      verification: (r) => text(r.verification),
      source: (r) => text(r.source),
      updated_at: () => "now()",
    }),
    upsert("curriculum_topics", topics, {
      id: (r) => text(r.id),
      chapter_id: (r) => text(r.chapterId),
      name_en: (r) => text(r.nameEn),
      name_km: (r) => text(r.nameKm),
      sort: (r) => String(r.sort),
      verification: (r) => text(r.verification),
    }),
  );
}

const sql = `-- Generated by scripts/build-curriculum-seed.mjs from src/data/curriculum/.
-- Do not edit by hand. Run after supabase/schema.sql; safe to run again.

begin;
${parts.join("\n")}
commit;
`;

await mkdir(new URL("../supabase/seed/", import.meta.url), { recursive: true });
await writeFile(OUT, sql);
console.log(
  `Wrote supabase/seed/curriculum.sql: ${counts.versions} version(s), ${counts.tracks} track(s), ${counts.subjects} subject(s), ${counts.chapters} chapters, ${counts.topics} topics`,
);
