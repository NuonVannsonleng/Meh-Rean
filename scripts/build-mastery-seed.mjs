#!/usr/bin/env node
/**
 * Writes supabase/seed/mastery-rules.sql from src/data/learning/mastery-rules.json
 * (Learning OS 3.2): the rules the database uses for topic mastery, made the
 * active version, then every estimate brought up to it. Rebuild
 * supabase/setup-all.sql afterwards.
 *
 *   node scripts/build-mastery-seed.mjs
 */

import { readFile, writeFile } from "node:fs/promises";

const rules = JSON.parse(await readFile(new URL("../src/data/learning/mastery-rules.json", import.meta.url), "utf8"));
if (!Number.isInteger(rules.version) || rules.version < 1) throw new Error("mastery-rules.json needs a whole-number version");
const json = JSON.stringify(rules).replace(/'/g, "''");

await writeFile(
  new URL("../supabase/seed/mastery-rules.sql", import.meta.url),
  [
    "-- Generated by scripts/build-mastery-seed.mjs from src/data/learning/mastery-rules.json.",
    "-- Do not edit by hand. Run after supabase/schema.sql; safe to run again.",
    "",
    "begin;",
    `insert into public.mastery_rules (version, rules) values (${rules.version}, '${json}'::jsonb)`,
    "on conflict (version) do update set rules = excluded.rules;",
    `update public.mastery_rules set active = false where active and version <> ${rules.version};`,
    `update public.mastery_rules set active = true where version = ${rules.version} and not active;`,
    "select public.refresh_all_topic_mastery();",
    "commit;",
    "",
  ].join("\n"),
);
console.log(`supabase/seed/mastery-rules.sql: version ${rules.version}`);
