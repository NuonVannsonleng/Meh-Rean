/**
 * Writes supabase/seed/demo-papers.sql from src/data/demo/*.json.
 *
 *   node scripts/build-demo-seed.mjs
 *
 * Run the SQL after supabase/schema.sql and supabase/seed/curriculum.sql. It
 * upserts by id, so it is safe to run again, and never deletes anything.
 * Everything it writes is marked demo and provisional.
 */

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { flattenCurriculum } from "../src/lib/curriculum.ts";
import { buildDemoPapers } from "../src/lib/papers.ts";

const ROOT = new URL("../", import.meta.url);
const text = (value) => (value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`);
const json = (value) => `${text(JSON.stringify(value))}::jsonb`;
const num = (value) => (value === null || value === undefined ? "null" : String(value));

const chapters = [];
for (const file of (await readdir(new URL("src/data/curriculum/", ROOT))).filter((name) => name.endsWith(".json"))) {
  chapters.push(...flattenCurriculum(JSON.parse(await readFile(new URL(`src/data/curriculum/${file}`, ROOT), "utf8"))).chapters);
}

const statements = [];
let counts = { papers: 0, questions: 0 };
for (const file of (await readdir(new URL("src/data/demo/", ROOT))).filter((name) => name.endsWith(".json")).sort()) {
  const papers = buildDemoPapers(JSON.parse(await readFile(new URL(`src/data/demo/${file}`, ROOT), "utf8")), chapters);
  statements.push(`-- ${file}`);
  for (const paper of papers) {
    counts.papers += 1;
    statements.push(`insert into public.exam_papers (id, subject_id, year, title_en, title_km, duration_minutes, duration_source, origin, source, verification)
values (${text(paper.id)}, ${text(paper.subjectId)}, ${paper.year}, ${text(paper.titleEn)}, ${text(paper.titleKm)}, ${num(paper.durationMinutes)}, ${text(paper.durationSource)}, ${text(paper.origin)}, ${text(paper.source)}, ${text(paper.verification)})
on conflict (id) do update set title_en = excluded.title_en, title_km = excluded.title_km, duration_minutes = excluded.duration_minutes,
  duration_source = excluded.duration_source, source = excluded.source, verification = excluded.verification;`);
    for (const { position, points, question: q } of paper.questions) {
      counts.questions += 1;
      const s = q.solution;
      statements.push(`insert into public.questions (id, chapter_id, topic_id, year, type, content, choices, images, difficulty, language, origin, source, verification)
values (${text(q.id)}, ${text(q.chapterId)}, ${text(q.topicId)}, ${num(q.year)}, ${text(q.type)}, ${text(q.content)}, ${json(q.choices)}, '[]'::jsonb, ${num(q.difficulty)}, ${text(q.language)}, ${text(q.origin)}, ${text(q.source)}, ${text(q.verification)})
on conflict (id) do update set chapter_id = excluded.chapter_id, topic_id = excluded.topic_id, year = excluded.year, content = excluded.content,
  choices = excluded.choices, difficulty = excluded.difficulty, language = excluded.language, source = excluded.source;
insert into public.question_solutions (question_id, answer, correct_choice, numeric_answer, numeric_tolerance, steps, origin, source, verification)
values (${text(q.id)}, ${text(s.answer)}, ${text(s.correctChoice)}, ${num(s.numericAnswer)}, ${num(s.numericTolerance)}, ${json(s.steps)}, ${text(s.origin)}, ${text(s.source)}, ${text(s.verification)})
on conflict (question_id) do update set answer = excluded.answer, correct_choice = excluded.correct_choice, numeric_answer = excluded.numeric_answer,
  numeric_tolerance = excluded.numeric_tolerance, steps = excluded.steps, source = excluded.source;
insert into public.exam_paper_questions (paper_id, question_id, position, points)
values (${text(paper.id)}, ${text(q.id)}, ${position}, ${num(points)})
on conflict (paper_id, question_id) do update set position = excluded.position, points = excluded.points;`);
    }
  }
}

await mkdir(new URL("supabase/seed/", ROOT), { recursive: true });
await writeFile(
  new URL("supabase/seed/demo-papers.sql", ROOT),
  `-- Generated by scripts/build-demo-seed.mjs from src/data/demo/. Do not edit by hand.
-- DEMO practice papers and questions, not official BacII content. Run after
-- supabase/schema.sql and supabase/seed/curriculum.sql; safe to run again.

begin;
${statements.join("\n\n")}
commit;
`,
);
console.log(`Wrote supabase/seed/demo-papers.sql: ${counts.papers} demo papers, ${counts.questions} demo questions`);
