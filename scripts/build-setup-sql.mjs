#!/usr/bin/env node
/**
 * Writes supabase/setup-all.sql: the whole schema, then the curriculum,
 * demo-paper, past-paper, topic-link and mastery-rule seeds, then a schema-cache
 * reload — one file to paste into the Supabase SQL editor to bring a
 * database up to date. Safe to run again.
 *
 *   npm run build:setup-sql
 */

import { readFileSync, writeFileSync } from "node:fs";

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8").trim();
const parts = [
  ["supabase/schema.sql", read("supabase/schema.sql")],
  ["supabase/seed/curriculum.sql", read("supabase/seed/curriculum.sql")],
  ["supabase/seed/demo-papers.sql", read("supabase/seed/demo-papers.sql")],
  ["supabase/seed/past-papers.sql", read("supabase/seed/past-papers.sql")],
  ["supabase/seed/concept-links.sql", read("supabase/seed/concept-links.sql")],
  ["supabase/seed/mastery-rules.sql", read("supabase/seed/mastery-rules.sql")],
];

const out = [
  "-- Generated by scripts/build-setup-sql.mjs. Do not edit by hand.",
  "-- Everything Meh Rean needs in Supabase, in order: schema, curriculum, demo",
  "-- papers, real past papers, topic links, mastery rules. Paste it all into Supabase → SQL Editor → New query → Run.",
  "-- Safe to run again; it never deletes your users, posts or messages.",
  "",
  ...parts.flatMap(([name, sql]) => [`-- ===== ${name} =====`, sql, ""]),
  "-- Let the API see the new tables straight away.",
  "notify pgrst, 'reload schema';",
  "",
].join("\n");

writeFileSync(new URL("../supabase/setup-all.sql", import.meta.url), out);
console.log(`supabase/setup-all.sql: ${(out.length / 1024).toFixed(0)} KB`);
