#!/usr/bin/env node
/**
 * Writes supabase/setup-all.sql: the whole schema, then the curriculum,
 * demo-paper, past-paper, topic-link and mastery-rule seeds, then a schema-cache
 * reload — one file to paste into the Supabase SQL editor to bring a
 * database up to date. Safe to run again.
 *
 *   npm run build:setup-sql
 */

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8").trim();
const parts = [
  ["supabase/schema.sql", read("supabase/schema.sql")],
  ["supabase/seed/curriculum.sql", read("supabase/seed/curriculum.sql")],
  ["supabase/seed/demo-papers.sql", read("supabase/seed/demo-papers.sql")],
  ["supabase/seed/past-papers.sql", read("supabase/seed/past-papers.sql")],
  ["supabase/seed/concept-links.sql", read("supabase/seed/concept-links.sql")],
  ["supabase/seed/mastery-rules.sql", read("supabase/seed/mastery-rules.sql")],
];

const out = [
  "-- Generated by scripts/build-setup-sql.mjs. Do not edit by hand.",
  "-- Everything Meh Rean needs in Supabase, in order: schema, curriculum, demo",
  "-- papers, real past papers, topic links, mastery rules. Paste it all into Supabase → SQL Editor → New query → Run.",
  "-- Safe to run again; it never deletes your users, posts or messages.",
  "",
  ...parts.flatMap(([name, sql]) => [`-- ===== ${name} =====`, sql, ""]),
  "-- Let the API see the new tables straight away.",
  "notify pgrst, 'reload schema';",
  "",
].join("\n");

writeFileSync(new URL("../supabase/setup-all.sql", import.meta.url), out);
console.log(`supabase/setup-all.sql: ${(out.length / 1024).toFixed(0)} KB`);

// The SQL editor refuses a query over about 1 MB, so the same SQL is also
// written as numbered parts, split only between whole transactions: the
// schema, and each seed (past-papers.sql holds one transaction per subject).
const PART_LIMIT = 600 * 1024;
const pieces = parts.flatMap(([name, sql]) => {
  const chunks = name.endsWith("past-papers.sql") ? sql.split(/\n\n(?=-- kh-grade12-)/) : [sql];
  return chunks.map((chunk, index) => `-- ===== ${name}${chunks.length > 1 ? ` (${index + 1}/${chunks.length})` : ""} =====\n${chunk}`);
});
const files = [];
for (const piece of pieces) {
  if (Buffer.byteLength(piece) > PART_LIMIT) throw new Error(`${piece.slice(0, 80)}… is over ${PART_LIMIT / 1024} KB on its own; split that seed`);
  const last = files.at(-1);
  if (last !== undefined && Buffer.byteLength(last) + Buffer.byteLength(piece) + 2 <= PART_LIMIT) files[files.length - 1] = `${last}\n\n${piece}`;
  else files.push(piece);
}
files[files.length - 1] += "\n\n-- Let the API see the new tables straight away.\nnotify pgrst, 'reload schema';";
const dir = new URL("../supabase/setup-parts/", import.meta.url);
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir, { recursive: true });
files.forEach((sql, index) => {
  writeFileSync(
    new URL(`${String(index + 1).padStart(2, "0")}.sql`, dir),
    `-- Generated by scripts/build-setup-sql.mjs: part ${index + 1} of ${files.length} of supabase/setup-all.sql, for the\n-- Supabase SQL editor (which refuses queries over about 1 MB). Run the parts in order.\n\n${sql}\n`,
  );
});
console.log(`supabase/setup-parts/: ${files.length} parts, largest ${(Math.max(...files.map((sql) => Buffer.byteLength(sql))) / 1024).toFixed(0)} KB`);
